#!/usr/bin/env node
/**
 * Equipment build/validation tool.
 *
 * Reads shared/data/equipment.json, validates it, and generates
 * shared/js/equipment-data.js (inline data for the browser client) plus
 * client/js/items.generated.js (per-item client classes + EntityFactory wiring).
 *
 * Usage: node tools/equipment/build.js
 */

var fs = require('fs'),
    path = require('path');

var ROOT = path.resolve(__dirname, '../..');
var DATA_FILE = path.join(ROOT, 'shared/data/equipment.json');
var OUT_DATA = path.join(ROOT, 'shared/js/equipment-data.js');
var OUT_ITEMS = path.join(ROOT, 'client/js/items.generated.js');
var OUT_SPRITES = path.join(ROOT, 'client/js/sprites.generated.js');
var SPRITES_DIR = path.join(ROOT, 'client/sprites');

var errors = [];
var warnings = [];

function fail(msg) { errors.push(msg); }
function warn(msg) { warnings.push(msg); }

function readJson(file) {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function validate(raw) {
    if(!raw.types || typeof raw.types !== 'object') {
        fail("Missing or invalid `types` object.");
        return;
    }

    var seenIds = {};
    var seenNames = {};

    Object.keys(raw.types).forEach(function(typeName) {
        var key = typeName + 's';
        var list = raw[key];
        if(!Array.isArray(list)) {
            fail("Missing array `" + key + "` for declared type `" + typeName + "`.");
            return;
        }

        var seenRanks = {};
        list.forEach(function(entry, i) {
            var where = key + '[' + i + ']';
            if(typeof entry.id !== 'number') { fail(where + ': `id` must be a number.'); }
            if(!entry.name || typeof entry.name !== 'string') { fail(where + ': `name` is required.'); }
            if(typeof entry.rank !== 'number') { fail(where + ': `rank` must be a number.'); }
            if(entry.type && entry.type !== typeName) {
                fail(where + ': `type` (" + entry.type + ") does not match category (" + typeName + ").');
            }

            if(typeof entry.id === 'number') {
                if(seenIds[entry.id] !== undefined) {
                    fail(where + ': duplicate id ' + entry.id + ' (also used by ' + seenIds[entry.id] + ').');
                } else {
                    seenIds[entry.id] = entry.name || where;
                }
            }
            if(entry.name) {
                if(seenNames[entry.name] !== undefined) {
                    fail(where + ': duplicate name "' + entry.name + '".');
                } else {
                    seenNames[entry.name] = true;
                }
            }
            if(typeof entry.rank === 'number') {
                if(seenRanks[entry.rank] !== undefined) {
                    warn(where + ': duplicate rank ' + entry.rank + ' (ordering will be ambiguous).');
                } else {
                    seenRanks[entry.rank] = true;
                }
            }

            if(typeName === 'armor' && typeof entry.maxHp !== 'number') {
                warn(where + ': armor has no explicit `maxHp`; clients/server will fall back.');
            }

            // Sprite validation (allow reuse of existing sprite names).
            var sprite = entry.sprite || entry.name;
            var itemSprite = entry.itemSprite || ('item-' + entry.name);
            [sprite, itemSprite].forEach(function(s) {
                if(!fs.existsSync(path.join(SPRITES_DIR, s + '.json'))) {
                    fail(where + ': missing sprite file client/sprites/' + s + '.json');
                }
            });
        });
    });

    // Ensure no reserved kind id collisions with non-equipment kinds would be
    // silent; warn if an equipment id overlaps a known core kind range.
}

function generateDataFile(raw) {
    var clean = {};
    Object.keys(raw).forEach(function(k) {
        if(k.charAt(0) === '_' || k.charAt(0) === '$') { return; }
        clean[k] = raw[k];
    });
    var header = "// AUTO-GENERATED by tools/equipment/build.js from shared/data/equipment.json.\n" +
                 "// Do not edit by hand; edit the JSON and re-run `npm run equipment:build`.\n";
    var body = "var BQ_EQUIPMENT_DATA = " + JSON.stringify(clean, null, 4) + ";\n";
    fs.writeFileSync(OUT_DATA, header + body);
}

function generateItemClasses(raw) {
    var lines = [];
    lines.push("// AUTO-GENERATED by tools/equipment/build.js from shared/data/equipment.json.");
    lines.push("// Do not edit by hand; edit the JSON and re-run `npm run equipment:build`.");
    lines.push("define(['item'], function(Item) {");
    lines.push("    var Items = {};");
    lines.push("");

    var builders = [];

    Object.keys(raw.types || {}).forEach(function(typeName) {
        (raw[typeName + 's'] || []).forEach(function(entry) {
            var className = entry.name.charAt(0).toUpperCase() + entry.name.slice(1);
            var type = entry.type || typeName;
            lines.push("    Items." + className + " = Item.extend({");
            lines.push("        init: function(id) {");
            lines.push("            this._super(id, Types.Entities." + entry.name.toUpperCase() + ", \"" + type + "\");");
            lines.push("            this.lootMessage = " + JSON.stringify(entry.lootMessage || ('You pick up a ' + entry.name)) + ";");
            lines.push("        },");
            lines.push("    });");
            lines.push("");

            builders.push({ kind: entry.name.toUpperCase(), name: entry.name, className: className });
        });
    });

    lines.push("    // Map of entity-kind enum name -> item class name, consumed by");
    lines.push("    // entityfactory.js to register builders without a circular import.");
    lines.push("    Items._builders = [");
    builders.forEach(function(b, i) {
        lines.push("        { kind: \"" + b.kind + "\", name: " + JSON.stringify(b.name) + ", className: \"" + b.className + "\" }" + (i < builders.length - 1 ? "," : ""));
    });
    lines.push("    ];");
    lines.push("");
    lines.push("    return Items;");
    lines.push("});");
    lines.push("");

    fs.writeFileSync(OUT_ITEMS, lines.join("\n"));
}

function generateSprites() {
    var files = fs.readdirSync(SPRITES_DIR)
        .filter(function(f) { return /\.json$/.test(f); })
        .sort();

    var lines = [];
    lines.push("// AUTO-GENERATED by tools/equipment/build.js from client/sprites/*.json.");
    lines.push("// Do not edit by hand.");
    lines.push("define([");
    files.forEach(function(f) {
        lines.push("        'text!../sprites/" + f + "',");
    });
    lines.push("        ], function() {");
    lines.push("    var sprites = {};");
    lines.push("    _.each(arguments, function(spriteJson) {");
    lines.push("        var sprite = JSON.parse(spriteJson);");
    lines.push("        sprites[sprite.id] = sprite;");
    lines.push("    });");
    lines.push("    return sprites;");
    lines.push("});");
    lines.push("");
    fs.writeFileSync(OUT_SPRITES, lines.join("\n"));
}

function main() {
    var raw;
    try {
        raw = readJson(DATA_FILE);
    } catch(e) {
        console.error("Could not read " + DATA_FILE + ": " + e.message);
        process.exit(1);
    }

    validate(raw);

    warnings.forEach(function(w) { console.warn("WARN: " + w); });
    if(errors.length) {
        errors.forEach(function(e) { console.error("ERROR: " + e); });
        console.error("\nEquipment build FAILED with " + errors.length + " error(s). No files written.");
        process.exit(1);
    }

    generateDataFile(raw);
    generateItemClasses(raw);
    generateSprites();

    var count = 0;
    Object.keys(raw.types || {}).forEach(function(t) { count += (raw[t + 's'] || []).length; });
    console.log("Equipment build OK: " + count + " items across " +
                Object.keys(raw.types || {}).length + " type(s).");
    console.log("  wrote " + path.relative(ROOT, OUT_DATA));
    console.log("  wrote " + path.relative(ROOT, OUT_ITEMS));
    console.log("  wrote " + path.relative(ROOT, OUT_SPRITES));
}

main();
